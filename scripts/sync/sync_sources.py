GUIDELINE_ID = re.compile(r"^\d+(\.\d+)*$")


def guideline_sections(html: str):
    """Yield (number, title, body) for every numbered App Review guideline."""
    soup = BeautifulSoup(html, "lxml")
    root = soup.select_one("main") or soup
    seen = set()
    for anchor in root.find_all(id=GUIDELINE_ID):
        number = anchor["id"]
        item = anchor if anchor.name == "li" else anchor.find_parent("li")
        if item is None or number in seen:
            continue
        seen.add(number)
        item = copy.copy(item)
        nested = [li for li in item.find_all("li")
                  if GUIDELINE_ID.match(li.get("id") or "") or li.find(id=GUIDELINE_ID)]
        for child in nested:
            if not child.decomposed:
                child.decompose()
        strong = item.find("strong")
        title = clean(strong.get_text(" ")) if strong else ""
        title = clean(re.sub(rf"^{re.escape(number)}\b", "", title)).rstrip(":")
        if strong:
            strong.decompose()
        body = clean(item.get_text(" "))
        if not title:
            words = body.split()
            title = " ".join(words[:8]) + (" …" if len(words) > 8 else "")
        yield number, title, body


def extract_apple_guidelines(html: str, today: str) -> Extract:
    sections = list(guideline_sections(html))
    if len(sections) < 50:
        raise RuntimeError(f"only {len(sections)} guidelines parsed; page layout probably changed")
    plain = clean(BeautifulSoup(html, "lxml").get_text(" "))
    m = re.search(r"Last Updated:?\s*([A-Z][a-z]+ \d{1,2},? \d{4})", plain)
    updated = parse_date(m.group(1)) if m else None

    text = f"Last Updated: {updated or 'unknown'}\n\n" + "\n\n".join(
        f"### {num} {title}\n{body}" for num, title, body in sections)

    rows = "\n".join(f"| [{num}](https://developer.apple.com/app-store/review/guidelines/#{num}) | {title} |"
                     for num, title, _ in sections)
    live_index = (
        f"{GENERATED_BANNER}\n# App Store Review Guidelines — Live Index\n\n"
        f"> Mirrors the section list of Apple's [App Store Review Guidelines]"
        f"(https://developer.apple.com/app-store/review/guidelines/).\n"
        f"> **Apple revision:** {updated or 'unknown'} · **Checked by policy-sync:** {today}\n\n"
        "Curated summaries live in [README.md](./README.md). This file is regenerated weekly so the "
        "skill always knows which guideline numbers exist.\n\n"
        f"| Guideline | Title |\n|-----------|-------|\n{rows}\n"
    )
    ext = Extract(text=text, generated={APPLE_LIVE_INDEX: live_index})
    if updated:
        ext.updates[APPLE_REQ] = {"guidelines_last_updated": updated}
    return ext


def extract_apple_upcoming(html: str, today: str) -> Extract:
    soup = BeautifulSoup(html, "lxml")
    text = page_lines(select_root(soup, "main"))
    flat = clean(text)
    ext = Extract(text=text)
    upd = {}
    m = re.search(r"SDK minimum requirements Since ([A-Z][a-z]+ \d{1,2},? \d{4}).{0,120}?Xcode (\d+)"
                  r" or later using an SDK for iOS (\d+)", flat)
    if m:
        upd.update({"sdk_minimum.effective": parse_date(m.group(1)),
                    "sdk_minimum.xcode": int(m.group(2)), "sdk_minimum.sdk": int(m.group(3))})
    m = re.search(r"minimum system requirements Since ([A-Z][a-z]+ \d{1,2},? \d{4}).{0,120}?"
                  r"must target iOS (\d+) or later", flat)
    if m:
        upd.update({"deployment_target_minimum.effective": parse_date(m.group(1)),
                    "deployment_target_minimum.ios": int(m.group(2))})
    if upd:
        ext.updates[APPLE_REQ] = upd
    else:
        ext.notes.append("Could not parse SDK / deployment-target minimums; review the page manually.")
    return ext


def extract_rss(xml: str, today: str) -> Extract:
    soup = BeautifulSoup(xml, "xml")
    lines = []
    for item in soup.find_all("item")[:40]:
        title = clean(item.title.get_text()) if item.title else ""
        link = clean(item.link.get_text()) if item.link else ""
        date = item.pubDate.get_text() if item.pubDate else ""
        try:
            date = dt.datetime.strptime(date[:16], "%a, %d %b %Y").date().isoformat()
        except ValueError:
            date = clean(date)
        lines.append(f"- {date} — {title} <{link}>")
    return Extract(text="\n".join(lines))


def extract_google_timeline(html: str, today: str) -> Extract:
    soup = BeautifulSoup(html, "lxml")
    rows = []
    for table in soup.select("article table, main table"):
        headers = [clean(th.get_text(" ")).lower() for th in table.find_all("th")]
        if not headers or "date" not in headers[0]:
            continue
        for tr in table.find_all("tr"):
            cells = [clean(td.get_text(" ")) for td in tr.find_all("td")]
            if len(cells) >= 2 and cells[0]:
                rows.append((parse_date(cells[0]) or cells[0], cells[1]))
    if not rows:
        raise RuntimeError("timeline table not found; page layout probably changed")
    text = "\n".join(f"- {d} — {t}" for d, t in rows)
    table = "\n".join(f"| {d} | {t.replace('|', '/')} |" for d, t in rows)
    doc = (
        f"{GENERATED_BANNER}\n# Google Play — Upcoming Policy Deadlines\n\n"
        "> Source: [Upcoming Android and Google Play deadlines]"
        "(https://developer.android.com/distribute/play-policies) · "
        "authoritative dates: [Play Console Policy Deadlines]"
        "(https://support.google.com/googleplay/android-developer/table/12921780)\n"
        f"> **Checked by policy-sync:** {today}\n\n"
        "| Date | Policy update |\n|------|---------------|\n" + table + "\n"
    )
    return Extract(text=text, generated={GOOGLE_DEADLINES: doc})


def extract_google_target_sdk(html: str, today: str) -> Extract:
    soup = BeautifulSoup(html, "lxml")
    text = page_lines(select_root(soup, "article"))
    flat = clean(text)
    upd = {}
    m = re.search(r"Starting ([A-Z][a-z]+ \d{1,2},? \d{4}):?\s*New apps and app updates must target "
                  r"Android \d+ \(API level (\d+)\)", flat)
    if m:
        upd["target_sdk.effective"] = parse_date(m.group(1))
        upd["target_sdk.new_apps_and_updates"] = int(m.group(2))
        tail = flat[m.end(): m.end() + 900]
        w = re.search(r"Wear OS and Android Automotive OS apps, which must target Android \d+ \(API level (\d+)\)", tail)
        t = re.search(r"Android TV and Android XR apps, which must target Android \d+ \(API level (\d+)\)", tail)
        e = re.search(r"Existing apps must target Android \d+ \(API level (\d+)\)", tail)
        x = re.search(r"extension to ([A-Z][a-z]+ \d{1,2},? \d{4})", flat)
        if w:
            upd["target_sdk.wear_os_and_automotive"] = int(w.group(1))
        if t:
            upd["target_sdk.tv_and_xr"] = int(t.group(1))
        if e:
            upd["target_sdk.existing_apps"] = int(e.group(1))
        if x:
            upd["target_sdk.extension_until"] = parse_date(x.group(1))
    ext = Extract(text=text)
    if upd:
        ext.updates[GOOGLE_REQ] = upd
    else:
        ext.notes.append("Could not parse the target API level sentence; review the page manually.")
    return ext


