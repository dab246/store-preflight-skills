# Main
# --------------------------------------------------------------------------- #
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", type=Path, help="write a Markdown report to this path")
    ap.add_argument("--only", help="comma-separated source ids to sync")
    ap.add_argument("--fixtures", type=Path, help="read <id>.html from this directory instead of the network")
    ap.add_argument("--today", default=dt.date.today().isoformat())
    args = ap.parse_args()

    config = json.loads(SOURCES_FILE.read_text(encoding="utf-8"))
    state = json.loads(STATE_FILE.read_text(encoding="utf-8")) if STATE_FILE.exists() else {}
    only = set(args.only.split(",")) if args.only else None
    SNAPSHOT_DIR.mkdir(parents=True, exist_ok=True)

    redact = redactor()
    rows, details, errors = [], [], 0
    changed_stores: set[str] = set()

    for src in config["sources"]:
        sid = src["id"]
        if only and sid not in only:
            continue
        try:
            if args.fixtures:
                raw = (args.fixtures / f"{sid}.html").read_text(encoding="utf-8")
            else:
                raw = fetch(src["url"])
            extractor = EXTRACTORS[src["extractor"]]
            ext = (extractor(raw, args.today, src.get("selector")) if src["extractor"] == "text"
                   else extractor(raw, args.today))
        except Exception as exc:  # report and continue with the other sources
            status = "⚠️ skipped (optional)" if src.get("optional") else "❌ error"
            errors += 0 if src.get("optional") else 1
            rows.append(f"| {src['store']} | [{src['title']}]({src['url']}) | {status} |")
            details.append(f"### {src['title']}\n\n`{type(exc).__name__}: {exc}`\n")
            continue

        ext.text = redact(ext.text)
        ext.generated = {path: redact(content) for path, content in ext.generated.items()}
        snap = SNAPSHOT_DIR / f"{sid}.md"
        old = snap.read_text(encoding="utf-8") if snap.exists() else ""
        digest = sha256(ext.text)
        notes = list(ext.notes)

        for path, updates in ext.updates.items():
            notes += apply_updates(path, updates, args.today)
        for path, content in ext.generated.items():
            if write_generated(path, content):
                notes.append(f"Regenerated `{path.relative_to(ROOT)}`")

        if state.get(sid, {}).get("sha256") == digest and old:
            status = "✅ unchanged"
        else:
            status = "🆕 new snapshot" if not old else "🔄 changed"
            snap.write_text(ext.text + "\n", encoding="utf-8")
            state[sid] = {"url": src["url"], "sha256": digest, "last_changed": args.today}
            if old:
                changed_stores.add(src["store"])
                if src["extractor"] == "apple_guidelines":
                    notes = changed_guidelines(old, ext.text) + notes
                diff = unified(old.rstrip("\n"), ext.text, f"sources/snapshots/{sid}.md")
                details.append(
                    f"### {src['title']}\n\n" + "".join(f"- {n}\n" for n in notes) +
                    f"\n<details><summary>Diff</summary>\n\n```diff\n{diff}\n```\n\n</details>\n")
                notes = []
        if notes:
            changed_stores.add(src["store"])
            details.append(f"### {src['title']}\n\n" + "".join(f"- {n}\n" for n in notes))
        rows.append(f"| {src['store']} | [{src['title']}]({src['url']}) | {status} |")

    STATE_FILE.write_text(json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    bump_skill_dates(changed_stores, args.today)

    report = (
        f"## 🛰️ Weekly policy sync — {args.today}\n\n"
        "| Store | Source | Status |\n|-------|--------|--------|\n" + "\n".join(rows) + "\n\n"
        + ("\n".join(details) if details else "_No upstream changes detected._\n")
        + "\n---\n### Maintainer checklist\n\n"
        "- [ ] Read each diff above and decide whether a rule, checklist or gotcha needs updating\n"
        "- [ ] Update `references/**/rules/*.md` and `last_verified` dates for affected rules\n"
        "- [ ] Add an entry under `[Unreleased]` in `CHANGELOG.md`\n"
    )
    if args.report:
        args.report.write_text(report, encoding="utf-8")
    print(report)

    if gh_out := os.environ.get("GITHUB_OUTPUT"):
        with open(gh_out, "a", encoding="utf-8") as fh:
            fh.write(f"changed={'true' if changed_stores else 'false'}\n")
            fh.write(f"stores={','.join(sorted(changed_stores))}\n")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
