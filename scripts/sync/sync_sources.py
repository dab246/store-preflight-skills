#!/usr/bin/env python3
"""Weekly policy sync for store-preflight-skills.

Fetches the official Apple and Google policy sources listed in sources.json,
normalises each page to plain text, and compares it with the snapshot stored in
sources/snapshots/. When a source changes it:

  * rewrites the snapshot and records the change in sources/state.json
  * refreshes machine-readable thresholds in references/*/requirements.json
    (target SDK, Billing Library, Xcode SDK minimum, ...)
  * regenerates the live indexes (Apple guideline list, Play deadline timeline)
  * bumps the "*-synced" dates in SKILL.md
  * writes a Markdown report (with diffs) that the workflow uses as PR body

Weeks without upstream changes leave the working tree untouched, so the
workflow only opens a pull request when there is something to review.

Usage:
  python scripts/sync/sync_sources.py [--report report.md] [--only id1,id2]
                                      [--fixtures DIR] [--today YYYY-MM-DD]
"""
from __future__ import annotations

import argparse
import copy
import datetime as dt
import difflib
import hashlib
import json
import os
import re
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

try:
    import requests
    from bs4 import BeautifulSoup
except ImportError:  # pragma: no cover - guidance for local runs
    sys.exit("Missing dependencies: pip install -r scripts/sync/requirements.txt")

ROOT = Path(__file__).resolve().parents[2]
SOURCES_FILE = ROOT / "scripts" / "sync" / "sources.json"
STATE_FILE = ROOT / "sources" / "state.json"
SNAPSHOT_DIR = ROOT / "sources" / "snapshots"
APPLE_REQ = ROOT / "references" / "apple" / "requirements.json"
GOOGLE_REQ = ROOT / "references" / "google" / "requirements.json"
APPLE_LIVE_INDEX = ROOT / "references" / "apple" / "guidelines" / "live-index.md"
GOOGLE_DEADLINES = ROOT / "references" / "google" / "policies" / "upcoming-deadlines.md"
SKILL_FILE = ROOT / "SKILL.md"

USER_AGENT = (
    "Mozilla/5.0 (X11; Linux x86_64) store-preflight-skills policy-sync "
    "(+https://github.com/dab246/store-preflight-skills)"
)
MAX_DIFF_LINES = 250
GENERATED_BANNER = "<!-- Generated by scripts/sync/sync_sources.py. Do not edit by hand. -->"
NEWS_KEYWORDS = re.compile(
    r"guideline|requirement|review|privacy|age|sdk|deadline|policy|policies|"
    r"subscription|tracking|sign in|purchase|payment|entitlement|account",
    re.I,
)
MONTHS = {m: i for i, m in enumerate(
    ["january", "february", "march", "april", "may", "june", "july", "august",
     "september", "october", "november", "december"], start=1)}


@dataclass
class Extract:
    text: str
    # {path: {"dotted.key": value}} applied to JSON requirement files
    updates: dict = field(default_factory=dict)
    # {path: full file content} for generated Markdown files
    generated: dict = field(default_factory=dict)
    notes: list = field(default_factory=list)


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def parse_date(text: str) -> str | None:
    """'August 31, 2026' / 'August 31 2026' / 'Aug 31, 2026' -> '2026-08-31'."""
    m = re.search(r"([A-Z][a-z]+)\.?\s+(\d{1,2}),?\s+(\d{4})", text)
    if not m:
        return None
    month = next((v for k, v in MONTHS.items() if k.startswith(m.group(1).lower()[:3])), None)
    if not month:
        return None
    return f"{int(m.group(3)):04d}-{month:02d}-{int(m.group(2)):02d}"


def clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\xa0", " ")).strip()


def page_lines(node) -> str:
    for bad in node.select("script, style, noscript, nav, header, footer, svg, button"):
        bad.decompose()
    lines = [clean(line) for line in node.get_text("\n").splitlines()]
    return "\n".join(line for line in lines if line)


def select_root(soup, selector: str | None):
    if selector:
        for sel in selector.split(","):
            node = soup.select_one(sel.strip())
            if node is not None:
                return node
    return soup.select_one("article") or soup.select_one("main") or soup


def redactor():
    """Terms to mask in stored snapshots, read from the POLICY_SYNC_REDACT_TERMS secret.

    Comma-separated, case-insensitive. Keeping the list in a repository secret means
    the terms themselves are never committed.
    """
    terms = [t.strip() for t in os.environ.get("POLICY_SYNC_REDACT_TERMS", "").split(",") if t.strip()]
    if not terms:
        return lambda text: text
    rx = re.compile(r"\b(" + "|".join(re.escape(t) for t in terms) + r")\b", re.I)
    return lambda text: rx.sub("[redacted]", text)


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def fetch(url: str, retries: int = 3) -> str:
    last = None
    for attempt in range(retries):
        try:
            resp = requests.get(url, headers={"User-Agent": USER_AGENT}, timeout=45)
            resp.raise_for_status()
            if not resp.encoding or resp.encoding.lower() == "iso-8859-1":
                resp.encoding = "utf-8"  # servers often omit charset; RFC default is wrong here
            return resp.text
        except requests.RequestException as exc:  # network flake: back off
            last = exc
            time.sleep(2 ** (attempt + 1))
    raise RuntimeError(f"fetch failed for {url}: {last}")


