# --------------------------------------------------------------------------- #
# Applying results
# --------------------------------------------------------------------------- #
def set_dotted(data: dict, dotted: str, value) -> bool:
    keys = dotted.split(".")
    node = data
    for key in keys[:-1]:
        node = node.setdefault(key, {})
    if node.get(keys[-1]) == value:
        return False
    node[keys[-1]] = value
    return True


def apply_updates(path: Path, updates: dict, today: str) -> list[str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    changes = []
    for dotted, value in updates.items():
        if value is None:
            continue
        old = data
        for key in dotted.split("."):
            old = old.get(key) if isinstance(old, dict) else None
        if set_dotted(data, dotted, value):
            changes.append(f"`{path.relative_to(ROOT)}` → `{dotted}`: `{old}` → `{value}`")
    if changes:
        data["last_synced"] = today
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return changes


def write_generated(path: Path, content: str) -> bool:
    """Write a generated file, ignoring a change that only touches the 'Checked' date."""
    strip = lambda s: re.sub(r"Checked by policy-sync:\*\* \S+", "", s)  # noqa: E731
    if path.exists() and strip(path.read_text(encoding="utf-8")) == strip(content):
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def bump_skill_dates(stores: set[str], today: str) -> None:
    if not SKILL_FILE.exists() or not stores:
        return
    text = SKILL_FILE.read_text(encoding="utf-8")
    for store, key in (("apple", "apple-guidelines-synced"), ("google", "google-policies-synced")):
        if store in stores:
            text = re.sub(rf'({key}:\s*)"[^"]*"', rf'\g<1>"{today}"', text)
    SKILL_FILE.write_text(text, encoding="utf-8")


def changed_guidelines(old: str, new: str) -> list[str]:
    def parse(text):
        out, cur = {}, None
        for line in text.splitlines():
            if line.startswith("### "):
                cur = line[4:].split(" ", 1)[0]
                out[cur] = line
            elif cur:
                out[cur] += "\n" + line
        return out
    a, b = parse(old), parse(new)
    notes = []
    for num in sorted(set(a) | set(b), key=lambda n: [int(p) for p in n.split(".")]):
        if num not in a:
            notes.append(f"**{num}** added")
        elif num not in b:
            notes.append(f"**{num}** removed")
        elif a[num] != b[num]:
            notes.append(f"**{num}** changed")
    return notes


def unified(old: str, new: str, name: str) -> str:
    diff = list(difflib.unified_diff(old.splitlines(), new.splitlines(),
                                     f"a/{name}", f"b/{name}", lineterm="", n=1))
    if len(diff) > MAX_DIFF_LINES:
        diff = diff[:MAX_DIFF_LINES] + [f"... ({len(diff) - MAX_DIFF_LINES} more lines truncated)"]
    return "\n".join(diff)


